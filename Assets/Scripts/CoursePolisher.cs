using UnityEngine;

/// <summary>
/// Applies a restrained visual/audio polish pass while preserving the course layout.
/// The extra maze walls and static bumpers remain, but moving hazards and neon effects are removed.
/// </summary>
public static class CoursePolisher
{
    private const string RootName = "__CoursePolish_Clean";
    private const string LegacyRootName = "__CoursePolish";

    private sealed class Palette
    {
        public Material ground;
        public Material wall;
        public Material obstacle;
        public Material ball;
        public Material coin;
        public Material finish;
    }

    public static void Apply()
    {
        if (GameObject.Find(RootName) != null)
            return;

        RemoveLegacyPolish();

        GameObject root = new GameObject(RootName);
        Palette palette = CreatePalette();

        ApplyEnvironment();
        StyleExistingCourse(palette);
        ExtendMaze(root, palette);
        AddBumperClusters(root, palette);
        StylePlayerBall(palette);
        AddMusic(root);
    }

    private static void RemoveLegacyPolish()
    {
        GameObject legacyRoot = GameObject.Find(LegacyRootName);
        if (legacyRoot != null)
            DestroyGeneratedObject(legacyRoot);

        // Remove visual accents generated by the previous neon pass because they were
        // parented to existing course objects instead of the generated root.
        Transform[] transforms = Object.FindObjectsByType<Transform>(FindObjectsSortMode.None);
        foreach (Transform t in transforms)
        {
            if (t == null)
                continue;

            if (t.name == "Polish Rail" ||
                t.name == "Finish Beacon" ||
                t.name == "Orbital Ring A" ||
                t.name == "Orbital Ring B" ||
                t.name == "Ball Accent Light")
            {
                DestroyGeneratedObject(t.gameObject);
            }
        }

        GameObject ball = GameObject.Find("PlayerBall");
        if (ball != null)
        {
            TrailRenderer trail = ball.GetComponent<TrailRenderer>();
            if (trail != null)
                DestroyGeneratedComponent(trail);
        }
    }

    private static Palette CreatePalette()
    {
        return new Palette
        {
            // Low-contrast, neutral materials: readable without looking like a neon arena.
            ground = CreateLit("Clean Ground", new Color(0.18f, 0.22f, 0.25f), 0.04f, 0.30f),
            wall = CreateLit("Clean Walls", new Color(0.62f, 0.66f, 0.69f), 0.08f, 0.42f),
            obstacle = CreateLit("Clean Obstacles", new Color(0.72f, 0.34f, 0.16f), 0.05f, 0.28f),
            ball = CreateLit("Clean Player Ball", new Color(0.12f, 0.36f, 0.62f), 0.22f, 0.68f),
            coin = CreateLit("Clean Coin", new Color(0.95f, 0.66f, 0.16f), 0.52f, 0.62f),
            finish = CreateLit("Clean Finish", new Color(0.18f, 0.55f, 0.32f), 0.08f, 0.40f)
        };
    }

    private static void ApplyEnvironment()
    {
        Camera main = Camera.main;
        if (main != null)
        {
            main.clearFlags = CameraClearFlags.Skybox;
            main.farClipPlane = Mathf.Max(main.farClipPlane, 250f);
        }

        // Keep the requested background, but make it subtle rather than bright or neon.
        Texture2D skyTexture = Resources.Load<Texture2D>("Environment/Starfield");
        Shader skyShader = Shader.Find("Skybox/Panoramic");
        if (skyTexture != null && skyShader != null)
        {
            Material skybox = new Material(skyShader) { name = "Simple Starfield Skybox (Runtime)" };
            skybox.SetTexture("_MainTex", skyTexture);
            if (skybox.HasProperty("_Exposure"))
                skybox.SetFloat("_Exposure", 0.38f);
            if (skybox.HasProperty("_Rotation"))
                skybox.SetFloat("_Rotation", 18f);
            RenderSettings.skybox = skybox;
        }

        RenderSettings.fog = false;
        RenderSettings.ambientMode = UnityEngine.Rendering.AmbientMode.Trilight;
        RenderSettings.ambientSkyColor = new Color(0.28f, 0.31f, 0.36f);
        RenderSettings.ambientEquatorColor = new Color(0.20f, 0.22f, 0.25f);
        RenderSettings.ambientGroundColor = new Color(0.10f, 0.11f, 0.12f);

        Light[] lights = Object.FindObjectsByType<Light>(FindObjectsSortMode.None);
        foreach (Light light in lights)
        {
            if (light.type != LightType.Directional)
                continue;

            light.color = new Color(1f, 0.97f, 0.92f);
            light.intensity = 1.05f;
            light.transform.rotation = Quaternion.Euler(48f, -28f, 0f);
            break;
        }
    }

    private static void StyleExistingCourse(Palette p)
    {
        Renderer[] renderers = Object.FindObjectsByType<Renderer>(FindObjectsSortMode.None);
        foreach (Renderer renderer in renderers)
        {
            string objectName = renderer.gameObject.name;

            if (objectName == "Ground")
            {
                renderer.sharedMaterial = p.ground;
            }
            else if (objectName.StartsWith("Wall"))
            {
                renderer.sharedMaterial = p.wall;
            }
            else if (objectName.StartsWith("Obstacle"))
            {
                renderer.sharedMaterial = p.obstacle;
            }
            else if (objectName.StartsWith("Coin"))
            {
                renderer.sharedMaterial = p.coin;
            }
            else if (objectName == "Finish")
            {
                renderer.sharedMaterial = p.finish;
            }
        }
    }

    private static void ExtendMaze(GameObject root, Palette p)
    {
        // Preserve the additional maze layout from the previous pass.
        CreateWall(root.transform, "Maze West A", new Vector3(-20.0f, 0.75f, 6.0f), new Vector3(7.0f, 1.5f, 0.5f), p.wall);
        CreateWall(root.transform, "Maze West B", new Vector3(-14.0f, 0.75f, 11.0f), new Vector3(7.0f, 1.5f, 0.5f), p.wall);
        CreateWall(root.transform, "Maze North Center", new Vector3(-5.0f, 0.75f, 13.0f), new Vector3(6.0f, 1.5f, 0.5f), p.wall);
        CreateWall(root.transform, "Maze South East", new Vector3(20.0f, 0.75f, -14.0f), new Vector3(6.0f, 1.5f, 0.5f), p.wall);
        CreateWall(root.transform, "Maze Finish Approach", new Vector3(20.0f, 0.75f, 13.7f), new Vector3(6.5f, 1.5f, 0.5f), p.wall);
    }

    private static void AddBumperClusters(GameObject root, Palette p)
    {
        // Keep the static obstacle cluster; only the moving spinners were removed.
        CreateBumper(root.transform, "Bumper A", new Vector3(8.2f, 0f, 3.7f), p.obstacle);
        CreateBumper(root.transform, "Bumper B", new Vector3(11.0f, 0f, 5.0f), p.obstacle);
        CreateBumper(root.transform, "Bumper C", new Vector3(12.2f, 0f, 2.2f), p.obstacle);
    }

    private static void StylePlayerBall(Palette p)
    {
        GameObject ball = GameObject.Find("PlayerBall");
        if (ball == null)
            return;

        Renderer renderer = ball.GetComponent<Renderer>();
        if (renderer != null)
            renderer.sharedMaterial = p.ball;
    }

    private static void AddMusic(GameObject root)
    {
        AudioClip clip = Resources.Load<AudioClip>("Audio/OrbitCourseLoop");
        if (clip == null)
        {
            Debug.LogWarning("CoursePolisher could not load the background music clip.");
            return;
        }

        AudioSource source = root.AddComponent<AudioSource>();
        source.clip = clip;
        source.loop = true;
        source.playOnAwake = true;
        source.spatialBlend = 0f;
        source.volume = 0.22f;
        source.priority = 64;

        if (Application.isPlaying)
            source.Play();
    }

    private static void CreateWall(Transform parent, string name, Vector3 position, Vector3 scale, Material material)
    {
        GameObject wall = GameObject.CreatePrimitive(PrimitiveType.Cube);
        wall.name = name;
        wall.transform.SetParent(parent);
        wall.transform.position = position;
        wall.transform.localScale = scale;
        wall.GetComponent<Renderer>().sharedMaterial = material;
    }

    private static void CreateBumper(Transform parent, string name, Vector3 position, Material material)
    {
        GameObject bumper = GameObject.CreatePrimitive(PrimitiveType.Cylinder);
        bumper.name = name;
        bumper.transform.SetParent(parent);
        bumper.transform.position = new Vector3(position.x, 0.75f, position.z);
        bumper.transform.localScale = new Vector3(0.95f, 0.75f, 0.95f);
        bumper.GetComponent<Renderer>().sharedMaterial = material;
    }

    private static Material CreateLit(string name, Color color, float metallic, float smoothness)
    {
        Shader shader = Shader.Find("Universal Render Pipeline/Lit");
        if (shader == null)
            shader = Shader.Find("Standard");
        if (shader == null)
            shader = Shader.Find("Diffuse");

        Material material = new Material(shader) { name = name };

        if (material.HasProperty("_BaseColor"))
            material.SetColor("_BaseColor", color);
        else if (material.HasProperty("_Color"))
            material.SetColor("_Color", color);

        if (material.HasProperty("_Metallic"))
            material.SetFloat("_Metallic", metallic);
        if (material.HasProperty("_Smoothness"))
            material.SetFloat("_Smoothness", smoothness);
        if (material.HasProperty("_Glossiness"))
            material.SetFloat("_Glossiness", smoothness);

        return material;
    }

    private static void DestroyGeneratedComponent(Object target)
    {
        if (target == null)
            return;

        if (Application.isPlaying)
            Object.Destroy(target);
        else
            Object.DestroyImmediate(target);
    }

    private static void DestroyGeneratedObject(GameObject target)
    {
        if (target == null)
            return;

        if (Application.isPlaying)
            Object.Destroy(target);
        else
            Object.DestroyImmediate(target);
    }
}
